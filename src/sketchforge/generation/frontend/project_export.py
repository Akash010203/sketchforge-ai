"""Project export: renders every PlannedFile to a final text string.

This is the dispatch table: given a PlannedFile and a ProjectPlan, produce the
appropriate source text.  All generators are collected here so that
``file_tree.materialise`` has a single import point.
"""
from __future__ import annotations

from sketchforge.generation.app_specification import AppSpec, PageSpec
from sketchforge.generation.project_planner import PlannedFile, ProjectPlan


def render_file(pf: PlannedFile, plan: ProjectPlan) -> str | None:
    """Return the source text for a planned file, or None to skip."""
    g = pf.generator

    if g == "scaffold":
        return _scaffold(pf, plan)
    if g == "component":
        return _component(pf, plan)
    if g == "page":
        return _page(pf, plan)
    if g == "page_html":
        return _page_html(pf, plan)
    if g == "page_js":
        return _page_js(pf, plan)
    if g == "style_global":
        return _style_global(pf, plan)
    if g == "style_module":
        return _style_module(pf, plan)
    if g == "types":
        return _types(pf, plan)
    if g == "readme":
        return _readme(pf, plan)
    if g in ("backend_models", "backend_db", "backend_logic", "backend_schema", "backend_test",
             "backend_api", "backend_auth", "backend_prisma", "backend_alembic_ini",
             "backend_migration_env", "backend_migration_template", "backend_requirements",
             "backend_prisma_package"):
        return _backend(pf, plan)
    return None


# ---------------------------------------------------------------------------
# Scaffold files
# ---------------------------------------------------------------------------

def _scaffold(pf: PlannedFile, plan: ProjectPlan) -> str:
    spec = plan.spec
    name = pf.relative_path

    if name == "package.json":
        return _package_json(spec)
    if name == "tsconfig.json":
        return _tsconfig()
    if name == "vite.config.ts":
        return _vite_config(spec)
    if name == "index.html":
        return _index_html(spec)
    if name == "src/main.tsx":
        return _main_tsx()
    if name == "src/App.tsx":
        return _app_tsx(spec)
    if name == "src/router.tsx":
        return _router_tsx(spec)
    return f"// {name} — generated by SketchForge\n"



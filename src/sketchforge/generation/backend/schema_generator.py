"""SQLite schema and typed model generators."""
from __future__ import annotations

from sketchforge.generation.app_specification import AppSpec, EntitySpec, FieldSpec

# SQL Schema
# ---------------------------------------------------------------------------

def generate_schema_sql(spec: AppSpec, dialect: str | None = None) -> str:
    dialect = dialect or spec.database
    if dialect not in {"sqlite", "postgresql", "mysql"}:
        raise ValueError(f"Unsupported SQL dialect: {dialect}")
    for entity in spec.entities:
        _check_identifier(entity.primary_key)
        _check_identifier(_snake(entity.name))
        for field in entity.fields:
            _check_identifier(field.name)
    lines: list[str] = [
        "-- Generated by SketchForge",
        f"-- {dialect.title()} schema for " + spec.name,
        "",
    ]
    if dialect == "sqlite":
        lines.extend(["PRAGMA journal_mode=WAL;", "PRAGMA foreign_keys=ON;", ""])
    for entity in spec.entities:
        lines.extend(_table_ddl(entity, dialect))
        lines.append("")
    return "\n".join(lines)


def _table_ddl(entity: EntitySpec, dialect: str = "sqlite") -> list[str]:
    table = _snake(entity.name)
    lines = [f"CREATE TABLE IF NOT EXISTS {table} ("]
    pk = ("INTEGER PRIMARY KEY AUTOINCREMENT" if dialect == "sqlite" else
          "SERIAL PRIMARY KEY" if dialect == "postgresql" else "INTEGER PRIMARY KEY AUTO_INCREMENT")
    cols = [f"  {entity.primary_key} {pk}"]
    for field in entity.fields:
        col_type = _sql_type(field.type, dialect)
        nullable = " NOT NULL" if field.required else ""
        cols.append(f"  {field.name} {col_type}{nullable}")
    if entity.timestamps:
        time_type = "TEXT" if dialect == "sqlite" else "TIMESTAMP"
        default = "datetime('now')" if dialect == "sqlite" else "CURRENT_TIMESTAMP"
        cols.append(f"  created_at {time_type} DEFAULT ({default})")
        update_suffix = " ON UPDATE CURRENT_TIMESTAMP" if dialect == "mysql" else ""
        cols.append(f"  updated_at {time_type} DEFAULT ({default}){update_suffix}")
    lines.append(",\n".join(cols))
    lines.append(");")
    if not entity.timestamps:
        return lines
    if dialect == "postgresql":
        lines += ["", f"CREATE OR REPLACE FUNCTION update_{table}_updated_at() RETURNS TRIGGER AS $$",
                  "BEGIN", "  NEW.updated_at = CURRENT_TIMESTAMP;", "  RETURN NEW;", "END;",
                  "$$ LANGUAGE plpgsql;", "", f"DROP TRIGGER IF EXISTS update_{table}_updated_at ON {table};",
                  f"CREATE TRIGGER update_{table}_updated_at BEFORE UPDATE ON {table}",
                  f"FOR EACH ROW EXECUTE FUNCTION update_{table}_updated_at();"]
        return lines
    if dialect == "mysql":
        return lines
    lines.append("")
    lines.append(
        f"CREATE TRIGGER IF NOT EXISTS update_{table}_updated_at"
    )
    lines.append(f"  AFTER UPDATE ON {table}")
    lines.append(f"  FOR EACH ROW")
    lines.append(
        f"  BEGIN UPDATE {table} SET updated_at = datetime('now') WHERE {entity.primary_key} = NEW.{entity.primary_key}; END;"
    )
    return lines


def _sql_type(field_type: str, dialect: str = "sqlite") -> str:
    if dialect == "postgresql":
        return {"text": "TEXT", "email": "VARCHAR(320)", "password": "TEXT", "number": "DOUBLE PRECISION", "select": "TEXT"}.get(field_type, "TEXT")
    if dialect == "mysql":
        return {"text": "TEXT", "email": "VARCHAR(320)", "password": "TEXT", "number": "DOUBLE", "select": "VARCHAR(255)"}.get(field_type, "TEXT")
    return {
        "text": "TEXT",
        "email": "TEXT",
        "password": "TEXT",
        "number": "REAL",
        "select": "TEXT",
    }.get(field_type, "TEXT")



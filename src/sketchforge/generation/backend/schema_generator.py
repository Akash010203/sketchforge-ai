def render_backend_file(pf, plan) -> str:
    """Dispatch a planned backend file to its focused generator module."""
    from sketchforge.generation.backend.test_generator import generate_test_py

    from sketchforge.generation.backend.targets import (
        alembic_ini, api_source, auth_source, migration_env, prisma_schema,
        migration_template, sqlalchemy_logic, sqlalchemy_models,
    )
    generators = {
        "backend_schema": generate_schema_sql,
        "backend_models": generate_models_py,
        "backend_db": generate_database_py,
        "backend_logic": generate_logic_py,
        "backend_test": generate_test_py,
    }
    if pf.generator == "backend_models" and (plan.spec.orm == "sqlalchemy" or plan.spec.database != "sqlite"):
        return sqlalchemy_models(plan.spec)
    if pf.generator == "backend_logic" and (plan.spec.orm == "sqlalchemy" or plan.spec.database != "sqlite"):
        return sqlalchemy_logic(plan.spec)
    if pf.generator == "backend_schema":
        return generate_schema_sql(plan.spec)
    extra = {
        "backend_api": lambda: api_source(plan.spec),
        "backend_auth": auth_source,
        "backend_prisma": lambda: prisma_schema(plan.spec),
        "backend_alembic_ini": alembic_ini,
        "backend_migration_env": migration_env,
        "backend_migration_template": migration_template,
        "backend_requirements": lambda: _requirements(plan.spec),
        "backend_prisma_package": lambda: _prisma_package(),
    }
    if pf.generator in extra:
        return extra[pf.generator]()
    generator = generators.get(pf.generator)
    return generator(plan.spec) if generator else f"# {pf.relative_path} - generated by SketchForge\n"


def _requirements(spec: AppSpec) -> str:
    packages = []
    if spec.orm == "sqlalchemy" or spec.database != "sqlite":
        packages += ["SQLAlchemy>=2.0"]
    if spec.orm != "prisma":
        packages += {"sqlite": [], "postgresql": ["psycopg[binary]>=3.2"], "mysql": ["PyMySQL>=1.1"]}[spec.database]
    if spec.orm != "prisma":
        packages += {"flask": ["Flask>=3.0"], "fastapi": ["fastapi>=0.115", "uvicorn[standard]>=0.30"], "graphql": ["fastapi>=0.115", "uvicorn[standard]>=0.30", "strawberry-graphql[fastapi]>=0.240"]}[spec.api_target]
    if spec.authentication:
        packages += ["PyJWT>=2.9", "Werkzeug>=3.0", "Authlib>=1.3"]
    if spec.migrations:
        packages += ["alembic>=1.13"]
    return "\n".join(packages) + "\n"


def _prisma_package() -> str:
    import json
    return json.dumps({"private": True, "scripts": {"db:migrate": "prisma migrate dev", "db:deploy": "prisma migrate deploy", "db:generate": "prisma generate"}, "dependencies": {"@prisma/client": "^6.0.0"}, "devDependencies": {"prisma": "^6.0.0"}}, indent=2) + "\n"



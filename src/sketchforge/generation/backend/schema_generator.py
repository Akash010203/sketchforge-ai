# Python Models (dataclasses + sqlite3 helper)
# ---------------------------------------------------------------------------

def generate_models_py(spec: AppSpec) -> str:
    lines: list[str] = [
        '"""Data models — generated by SketchForge."""',
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass, field",
        "from typing import Optional",
        "",
    ]
    for entity in spec.entities:
        lines.extend(_dataclass(entity))
        lines.append("")
    return "\n".join(lines)


def _dataclass(entity: EntitySpec) -> list[str]:
    lines = ["@dataclass"]
    lines.append(f"class {entity.name}:")
    lines.append(f'    """Auto-generated model for {entity.name}."""')
    lines.append(f"    {entity.primary_key}: Optional[int] = None")
    for field in entity.fields:
        py_type = _py_type(field.type)
        default = '""' if py_type == "str" else "None"
        lines.append(f"    {field.name}: {py_type} = {default}")
    if entity.timestamps:
        lines.append("    created_at: Optional[str] = None")
        lines.append("    updated_at: Optional[str] = None")

    # to_dict helper
    lines.append("")
    lines.append("    def to_dict(self) -> dict:")
    lines.append("        from dataclasses import asdict")
    lines.append("        return asdict(self)")
    return lines


def _py_type(field_type: str) -> str:
    return {
        "text": "str",
        "email": "str",
        "password": "str",
        "number": "float",
        "select": "str",
    }.get(field_type, "str")


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def _snake(s: str) -> str:
    import re
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    s = re.sub(r"([a-z\d])([A-Z])", r"\1_\2", s)
    return s.lower().replace(" ", "_")


def _check_identifier(value: str) -> None:
    import keyword
    import re
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value) or keyword.iskeyword(value):
        raise ValueError(f"Invalid generated SQL/Python identifier: {value!r}")


